                        function smithNormalForm(inputMat) {
                            const m = inputMat.length;
                            const n = inputMat[0].length;
                            const mat = inputMat.map(row => [...row]);
                            const diag = [];
                            const minDim = Math.min(m, n);

                            for (let k = 0; k < minDim; k++) {
                                let changed = true;
                                let iterations = 0;
                                while (changed && iterations < 100) {
                                    changed = false;
                                    iterations++;
                                    // Find smallest nonzero in submatrix
                                    let minVal = Infinity, mi2 = -1, mj = -1;
                                    for (let i = k; i < m; i++) {
                                        for (let j = k; j < n; j++) {
                                            if (mat[i][j] !== 0 && Math.abs(mat[i][j]) < minVal) {
                                                minVal = Math.abs(mat[i][j]);
                                                mi2 = i; mj = j;
                                            }
                                        }
                                    }
                                    if (mi2 === -1) break;
                                    // Swap to (k,k)
                                    if (mi2 !== k) { [mat[k], mat[mi2]] = [mat[mi2], mat[k]]; changed = true; }
                                    if (mj !== k) {
                                        for (let i = 0; i < m; i++) { [mat[i][k], mat[i][mj]] = [mat[i][mj], mat[i][k]]; }
                                        changed = true;
                                    }
                                    if (mat[k][k] < 0) {
                                        for (let j = 0; j < n; j++) mat[k][j] = -mat[k][j];
                                    }
                                    // Eliminate column k
                                    for (let i = k + 1; i < m; i++) {
                                        if (mat[i][k] !== 0) {
                                            const q = Math.floor(mat[i][k] / mat[k][k]);
                                            for (let j = 0; j < n; j++) mat[i][j] -= q * mat[k][j];
                                            if (mat[i][k] !== 0) changed = true;
                                        }
                                    }
                                    // Eliminate row k
                                    for (let j = k + 1; j < n; j++) {
                                        if (mat[k][j] !== 0) {
                                            const q = Math.floor(mat[k][j] / mat[k][k]);
                                            for (let i = 0; i < m; i++) mat[i][j] -= q * mat[i][k];
                                            if (mat[k][j] !== 0) changed = true;
                                        }
                                    }
                                    // Check divisibility
                                    let allDiv = true;
                                    for (let i = k + 1; i < m && allDiv; i++) {
                                        for (let j = k + 1; j < n && allDiv; j++) {
                                            if (mat[i][j] % mat[k][k] !== 0) allDiv = false;
                                        }
                                    }
                                    if (!allDiv) {
                                        for (let i = k + 1; i < m; i++) {
                                            if (mat[i][k] === 0) {
                                                for (let j = k + 1; j < n; j++) {
                                                    if (mat[i][j] % mat[k][k] !== 0) {
                                                        for (let ii = 0; ii < m; ii++) mat[ii][k] += mat[ii][j];
                                                        changed = true;
                                                        break;
                                                    }
                                                }
                                                if (changed) break;
                                            }
                                        }
                                    }
                                }
                                if (mat[k][k] !== 0) diag.push(mat[k][k]);
                            }
                            return diag;
                        }

